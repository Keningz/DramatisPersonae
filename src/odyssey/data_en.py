CN = {'一': 1, '二': 2, '三': 3, '四': 4, '五': 5, '六': 6, '七': 7, '八': 8, '九': 9, '十': 10}


def cn_num(s):
    s = s.strip()
    if s == '十':
        return 10
    if s.startswith('十'):
        return 10 + CN[s[1]]
    if '十' in s:
        a, b = s.split('十')
        return CN[a] * 10 + (CN[b] if b else 0)
    return CN[s]


def book_en(bk):
    """'卷一、卷五' -> 'Books 1, 5'; '卷一至三、卷十五' -> 'Books 1–3, 15'."""
    parts = []
    count = 0
    for seg in bk.split('、'):
        seg = seg.replace('卷', '')
        if '至' in seg:
            a, b = seg.split('至')
            parts.append(f'{cn_num(a)}–{cn_num(b)}')
            count += 2
        else:
            parts.append(str(cn_num(seg)))
            count += 1
    return ('Books ' if count > 1 else 'Book ') + ', '.join(parts)
